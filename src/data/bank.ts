export const BANK_BY_SUBJECT: Record<string, BankEntry[]> = (() => {
  const map: Record<string, BankEntry[]> = {}
  for (const entry of BANK) {
    ;(map[entry.subject] ??= []).push(entry)
  }
  return map
})()

/**
 * Deterministically pick `count` entries from the bank.
 * The starting point rotates with the filter values, so repeated calls with the
 * same filters walk through the pool instead of returning the same head every time.
 */
export function pickQuestions(opts: {
  subject?: string
  grade?: string
  type?: QuestionType
  count: number
  avoidIds?: string[]
}): BankEntry[] {
  const avoid = new Set(opts.avoidIds ?? [])

  let pool = BANK.filter((b) => {
    if (opts.subject && b.subject !== opts.subject) return false
    if (opts.grade && !b.grades.includes('all') && !b.grades.includes(opts.grade)) return false
    if (opts.type && b.type !== opts.type) return false
    if (avoid.has(b.id)) return false
    return true
  })

  // trac-nghiem first when the caller did not constrain the type
  if (!opts.type) {
    pool = [...pool].sort((a, b) => (a.type === 'trac-nghiem' ? 0 : 1) - (b.type === 'trac-nghiem' ? 0 : 1))
  }

  if (pool.length <= opts.count) return pool

  const seed = hash(`${opts.subject ?? ''}|${opts.grade ?? ''}|${opts.type ?? ''}`)
  const start = seed % pool.length
  const out: BankEntry[] = []
  for (let i = 0; i < opts.count; i += 1) {
    out.push(pool[(start + i) % pool.length])
  }
  return out
}

function hash(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return Math.abs(h)
}
